(() => {
    'use strict';

    const body = document.body;
    if (!body) return;

    const profileModal = document.querySelector('[data-profile-modal]');
    const passwordModal = document.querySelector('[data-password-modal]');
    const passwordOtpModal = document.querySelector('[data-password-otp-modal]');
    const modals = [profileModal, passwordModal, passwordOtpModal].filter(Boolean);

    let lastTouchActivation = 0;

    const syncBodyLock = () => {
        const anyOpen = modals.some((modal) => !modal.hidden && modal.classList.contains('is-open'));
        body.classList.toggle('settings-modal-open', anyOpen);
    };

    const positionModalForVisualViewport = (modal) => {
        if (!modal || modal.hidden) return;
        const vv = window.visualViewport;
        if (!vv) {
            modal.style.removeProperty('--settings-vv-top');
            modal.style.removeProperty('--settings-vv-height');
            return;
        }

        modal.style.setProperty('--settings-vv-top', `${Math.max(0, vv.offsetTop)}px`);
        modal.style.setProperty('--settings-vv-height', `${Math.max(1, vv.height)}px`);
    };

    const closeAllExcept = (keep) => {
        modals.forEach((modal) => {
            if (modal === keep) return;
            modal.classList.remove('is-open');
            modal.hidden = true;
            modal.setAttribute('aria-hidden', 'true');
        });
    };

    const showModal = (modal) => {
        if (!modal) return;
        closeAllExcept(modal);
        modal.hidden = false;
        modal.setAttribute('aria-hidden', 'false');
        modal.classList.add('is-open');
        positionModalForVisualViewport(modal);
        syncBodyLock();

        window.requestAnimationFrame(() => {
            const focusTarget = modal.querySelector('input:not([type="hidden"]), button:not(.settings-modal-backdrop)');
            try {
                focusTarget?.focus({ preventScroll: true });
            } catch (_) {
                focusTarget?.focus();
            }
        });
    };

    const hideModal = (modal) => {
        if (!modal) return;
        modal.classList.remove('is-open');
        modal.hidden = true;
        modal.setAttribute('aria-hidden', 'true');
        syncBodyLock();
    };

    const delegatedActivate = (event) => {
        const target = event.target instanceof Element ? event.target : null;
        if (!target) return;

        const trigger = target.closest(
            '[data-profile-modal-open], [data-profile-modal-close], [data-password-modal-open], [data-password-modal-close], [data-password-otp-back], [data-profile-file-trigger], [data-password-toggle]'
        );
        if (!trigger) return;

        // On iPad/Safari pointerup is more reliable than waiting for a synthesized click.
        // Ignore the follow-up click generated by the same touch.
        if (event.type === 'pointerup') {
            if (event.pointerType === 'mouse') return;
            lastTouchActivation = Date.now();
        } else if (event.type === 'click' && Date.now() - lastTouchActivation < 700) {
            return;
        }

        event.preventDefault();
        event.stopPropagation();

        if (trigger.matches('[data-profile-modal-open]')) {
            showModal(profileModal);
            return;
        }

        if (trigger.matches('[data-profile-modal-close]')) {
            hideModal(profileModal);
            return;
        }

        if (trigger.matches('[data-password-modal-open]')) {
            showModal(passwordModal);
            return;
        }

        if (trigger.matches('[data-password-modal-close]')) {
            hideModal(passwordModal);
            return;
        }

        if (trigger.matches('[data-password-otp-back]')) {
            hideModal(passwordOtpModal);
            showModal(passwordModal);
            return;
        }

        if (trigger.matches('[data-profile-file-trigger]')) {
            const profileFile = document.querySelector('[data-profile-file]');
            profileFile?.click();
            return;
        }

        if (trigger.matches('[data-password-toggle]')) {
            const wrap = trigger.closest('.settings-password-input');
            const input = wrap?.querySelector('[data-password-input]');
            if (!input) return;

            const showing = input.type === 'text';
            input.type = showing ? 'password' : 'text';
            trigger.textContent = showing ? 'SHOW' : 'HIDE';
            try {
                input.focus({ preventScroll: true });
            } catch (_) {
                input.focus();
            }
        }
    };

    document.addEventListener('click', delegatedActivate, false);
    if ('PointerEvent' in window) {
        document.addEventListener('pointerup', delegatedActivate, { passive: false });
    }

    const profileFile = document.querySelector('[data-profile-file]');
    const profilePreview = document.querySelector('[data-profile-preview]');
    const fileName = document.querySelector('[data-profile-file-name]');
    const profileSave = document.querySelector('[data-profile-save]');

    profileFile?.addEventListener('change', () => {
        const file = profileFile.files?.[0];
        if (!file) {
            if (profileSave) profileSave.disabled = true;
            return;
        }

        if (fileName) fileName.textContent = file.name;
        if (profileSave) profileSave.disabled = false;

        const reader = new FileReader();
        reader.addEventListener('load', () => {
            if (profilePreview && typeof reader.result === 'string') {
                profilePreview.src = reader.result;
            }
        });
        reader.readAsDataURL(file);
    });

    const otpInput = document.querySelector('[data-settings-otp-input]');
    otpInput?.addEventListener('input', () => {
        otpInput.value = otpInput.value.replace(/\D/g, '').slice(0, 6);
    });

    const repositionOpenModals = () => {
        modals.forEach(positionModalForVisualViewport);
    };

    window.visualViewport?.addEventListener('resize', repositionOpenModals);
    window.visualViewport?.addEventListener('scroll', repositionOpenModals);
    window.addEventListener('orientationchange', () => {
        window.setTimeout(repositionOpenModals, 100);
    });

    if (body.dataset.openPasswordOtp === '1') {
        showModal(passwordOtpModal);
        window.setTimeout(() => otpInput?.focus(), 100);
    } else if (body.dataset.openPasswordModal === '1') {
        showModal(passwordModal);
    }

    document.addEventListener('keydown', (event) => {
        if (event.key !== 'Escape') return;
        if (passwordOtpModal && !passwordOtpModal.hidden) return;
        if (profileModal && !profileModal.hidden) {
            hideModal(profileModal);
            return;
        }
        if (passwordModal && !passwordModal.hidden) {
            hideModal(passwordModal);
        }
    });
})();
